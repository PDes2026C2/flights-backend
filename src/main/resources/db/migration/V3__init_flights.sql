CREATE SCHEMA IF NOT EXISTS flight;

CREATE TABLE IF NOT EXISTS flight.flights (
                                              id SERIAL PRIMARY KEY,
                                              capacity INT NOT NULL,
                                              airline VARCHAR(255) NOT NULL,
    departure_date TIMESTAMP NOT NULL,
    arrival_date TIMESTAMP NOT NULL,
    origin_city_id INT NOT NULL,
    destination_city_id INT NOT NULL,
    CONSTRAINT fk_flight_origin FOREIGN KEY (origin_city_id) REFERENCES world.cities(id),
    CONSTRAINT fk_flight_destination FOREIGN KEY (destination_city_id) REFERENCES world.cities(id)
    );

-- (Opcional) Tabla intermedia para pasajeros, si querés que Hibernate la encuentre lista
CREATE TABLE IF NOT EXISTS flight.flight_passenger (
                                                       flight_id INT NOT NULL,
                                                       passenger_id INT NOT NULL,
                                                       PRIMARY KEY (flight_id, passenger_id)
    );

